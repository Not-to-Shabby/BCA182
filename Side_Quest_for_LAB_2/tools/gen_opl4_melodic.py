#!/usr/bin/env python3
"""
gen_opl4_melodic.py
Generates 16-bit 22,050 Hz acoustic attack transient waveforms (Piano hammer,
Acoustic Guitar pick, and Electric Bass fret-clack) and writes them as const int16_t
Flash ROM tables to include/opl4_melodic_samples.h.

Used for the hybrid Yamaha RCM / AWM + FM synthesis engine.
"""

import math
import random
import os

FS = 22050.0

def clamp16(x):
    v = int(round(x))
    return max(-32767, min(32767, v))

def gen_piano_attack():
    """Acoustic Grand Piano: felt hammer compression + soundboard knock + inharmonic attack transient (~85 ms)."""
    n = int(0.085 * FS) # 1874 samples
    out = []
    rng = random.Random(505)
    f0 = 261.6256 # C4
    lp = 0.0
    for i in range(n):
        t = i / FS
        # Hammer strike noise burst in first 4 ms
        nz = rng.uniform(-1.0, 1.0) * math.exp(-t / 0.0035)
        lp += 0.45 * (nz - lp)
        # Soundboard wood thump (110 Hz + 260 Hz)
        thump = 0.65 * math.sin(2.0 * math.pi * 115.0 * t) * math.exp(-t / 0.022)
        # Inharmonic string strike modes (fundamental + early harmonics with rapid initial decay)
        h1 = math.sin(2.0 * math.pi * f0 * t) * math.exp(-t / 0.075)
        h2 = 0.72 * math.sin(2.0 * math.pi * (f0 * 2.003) * t) * math.exp(-t / 0.045)
        h3 = 0.48 * math.sin(2.0 * math.pi * (f0 * 3.012) * t) * math.exp(-t / 0.030)
        h4 = 0.35 * math.sin(2.0 * math.pi * (f0 * 4.025) * t) * math.exp(-t / 0.018)
        val = (thump * 0.45 + lp * 0.55 + h1 * 0.70 + h2 + h3 + h4) * 11500.0
        out.append(clamp16(val))
    return out

def gen_guitar_attack():
    """Acoustic Guitar: cellulose plectrum snap + spruce top-plate resonance (~65 ms)."""
    n = int(0.065 * FS) # 1433 samples
    out = []
    rng = random.Random(606)
    f0 = 164.8138 # E3
    bp = 0.0
    prev = 0.0
    for i in range(n):
        t = i / FS
        raw = rng.uniform(-1.0, 1.0)
        hp = raw - prev
        prev = raw
        bp += 0.35 * (hp - bp)
        pick = bp * math.exp(-t / 0.0040)
        # Body cavity Helmholtz mode (~105 Hz) + spruce top mode (~215 Hz)
        body = (0.55 * math.sin(2.0 * math.pi * 105.0 * t) +
                0.45 * math.sin(2.0 * math.pi * 215.0 * t)) * math.exp(-t / 0.025)
        # String harmonics
        s1 = math.sin(2.0 * math.pi * f0 * t) * math.exp(-t / 0.060)
        s2 = 0.65 * math.sin(2.0 * math.pi * (f0 * 2.0) * t) * math.exp(-t / 0.040)
        s3 = 0.40 * math.sin(2.0 * math.pi * (f0 * 3.0) * t) * math.exp(-t / 0.025)
        val = (pick * 0.70 + body * 0.40 + s1 * 0.75 + s2 + s3) * 11800.0
        out.append(clamp16(val))
    return out

def gen_bass_attack():
    """Fingered / Slap Bass: metal string-to-fret clack + fingerboard transient (~55 ms)."""
    n = int(0.055 * FS) # 1212 samples
    out = []
    rng = random.Random(707)
    f0 = 82.4069 # E2
    bp = 0.0
    prev = 0.0
    for i in range(n):
        t = i / FS
        raw = rng.uniform(-1.0, 1.0)
        hp = raw - prev
        prev = raw
        bp += 0.28 * (hp - bp)
        clack = bp * math.exp(-t / 0.0060)
        punch = math.sin(2.0 * math.pi * 65.0 * t) * math.exp(-t / 0.035)
        b1 = math.sin(2.0 * math.pi * f0 * t) * math.exp(-t / 0.050)
        b2 = 0.85 * math.sin(2.0 * math.pi * (f0 * 2.0) * t) * math.exp(-t / 0.035)
        val = (clack * 0.80 + punch * 0.50 + b1 * 0.65 + b2 * 0.75) * 12200.0
        out.append(clamp16(val))
    return out

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.normpath(os.path.join(here, "..", "include", "opl4_melodic_samples.h"))

    piano = gen_piano_attack()
    guitar = gen_guitar_attack()
    bass = gen_bass_attack()

    total_bytes = (len(piano) + len(guitar) + len(bass)) * 2

    lines = [
        "/**",
        " * @file opl4_melodic_samples.h",
        f" * @brief Acoustic attack transient WaveTables for Hybrid PCM+FM synthesis ({total_bytes} bytes in Flash).",
        " *        Generated by tools/gen_opl4_melodic.py.",
        " */",
        "",
        "#ifndef OPL4_MELODIC_SAMPLES_H_",
        "#define OPL4_MELODIC_SAMPLES_H_",
        "",
        "#include <stdint.h>",
        "",
        "#define OPL4_MELODIC_SAMPLE_RATE 22050U",
        "",
        f"#define OPL4_PCM_PIANO_LEN {len(piano)}U",
        f"#define OPL4_PCM_PIANO_ROOT_HZ 261.6256f /* C4 */",
        f"static const int16_t OPL4_PCM_PIANO[{len(piano)}] = {{",
    ]
    for i in range(0, len(piano), 16):
        lines.append("    " + ", ".join(str(x) for x in piano[i:i+16]) + ",")
    lines.append("};")
    lines.append("")

    lines.extend([
        f"#define OPL4_PCM_GUITAR_LEN {len(guitar)}U",
        f"#define OPL4_PCM_GUITAR_ROOT_HZ 164.8138f /* E3 */",
        f"static const int16_t OPL4_PCM_GUITAR[{len(guitar)}] = {{",
    ])
    for i in range(0, len(guitar), 16):
        lines.append("    " + ", ".join(str(x) for x in guitar[i:i+16]) + ",")
    lines.append("};")
    lines.append("")

    lines.extend([
        f"#define OPL4_PCM_BASS_LEN {len(bass)}U",
        f"#define OPL4_PCM_BASS_ROOT_HZ 82.4069f /* E2 */",
        f"static const int16_t OPL4_PCM_BASS[{len(bass)}] = {{",
    ])
    for i in range(0, len(bass), 16):
        lines.append("    " + ", ".join(str(x) for x in bass[i:i+16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("#endif /* OPL4_MELODIC_SAMPLES_H_ */")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated {out_path} ({total_bytes} bytes in Flash ROM, 0 B RAM)")

if __name__ == "__main__":
    main()
